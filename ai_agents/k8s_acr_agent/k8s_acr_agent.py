def get_aks_credentials(dry_run: bool) -> bool:
    cluster = get_env("AKS_CLUSTER_NAME", required=True)
    rg = get_env("RESOURCE_GROUP", required=True)
    print("\n" + "="*65)
    print("  PHASE 2 — Get AKS Credentials")
    print("="*65)
    print(f"  Cluster: {cluster}  |  RG: {rg}")

    rc, _, stderr = run_cmd(
        ["az", "aks", "get-credentials",
         "--resource-group", rg,
         "--name", cluster,
         "--overwrite-existing"],
        dry_run=dry_run,
    )
    if rc != 0:
        print(f"  [ERROR] Could not get AKS credentials: {stderr}")
        return False
    print("  ✓ kubectl configured for cluster.")
    return True


