class AcrPhase:
    def __init__(
        self,
        dry_run: bool,
        client: genai.Client,
        max_retries: int,
        image_name: str = None,
        image_tag: str = None,
        build_context_dir: Path = None,
        acr_name: str = None,
        resource_group: str = None,
    ):
        self.dry_run = dry_run
        self.client = client
        self.max_retries = max_retries
        self.acr_name = acr_name or get_env("ACR_NAME", required=True)
        self.acr_login_server = get_env("ACR_LOGIN_SERVER")
        self.image_name = image_name or get_env("IMAGE_NAME", "app")
        self.image_tag = image_tag or get_env("IMAGE_TAG", "latest")
        self.resource_group = resource_group or get_env("RESOURCE_GROUP", required=True)
        self.build_context_dir = build_context_dir or REPO_ROOT

    @property
    def full_image_ref(self) -> str:
        server = self.acr_login_server or f"{self.acr_name}.azurecr.io"
        return f"{server}/{self.image_name}:{self.image_tag}"

    def _build_cmd(self) -> list[str]:
        return [
            "az", "acr", "build",
            "--registry", self.acr_name,
            "--image", f"{self.image_name}:{self.image_tag}",
            "--resource-group", self.resource_group,
            str(self.build_context_dir),   # Build context (app folder or repo root)
        ]

    def _ask_gemini_fix(self, error_output: str) -> dict | None:
        dockerfile_content = ""
        dockerfile_path = REPO_ROOT / "dockerfile"
        if not dockerfile_path.exists():
            dockerfile_path = REPO_ROOT / "Dockerfile"
        if dockerfile_path.exists():
            dockerfile_content = dockerfile_path.read_text(encoding='utf-8', errors='replace')

        prompt = f"""You are an Azure DevOps and Docker expert.
The `az acr build` command failed with the following error.
Diagnose the issue and provide corrected file content if any file changes are needed.

## ACR BUILD ERROR
{error_output}

## CURRENT DOCKERFILE
```dockerfile
{dockerfile_content}
```

## ACR CONFIGURATION
- Registry name: {self.acr_name}
- Image: {self.image_name}:{self.image_tag}
- Resource group: {self.resource_group}

Respond ONLY with a JSON block inside ```json ... ```:
```json
{{
  "diagnosis": "Root cause explanation",
  "corrections": [
    {{
      "file_path": "relative/path/from/repo/root/to/file",
      "corrected_content": "Full corrected file content"
    }}
  ],
  "az_command_override": []
}}
```
- If the az command itself needs different arguments, put the full corrected command list in `az_command_override`.
- If no changes are needed (transient error), set corrections to [] and az_command_override to [].
"""
        try:
            from llm_client import generate_text_with_retry
            raw = generate_text_with_retry(self.client, prompt)
            if "```json" in raw:
                json_str = raw.split("```json")[1].split("```")[0].strip()
            elif "```" in raw:
                json_str = raw.split("```")[1].split("```")[0].strip()
            else:
                json_str = raw
            return json.loads(json_str)
        except Exception as exc:
            print(f"  [ERROR] Gemini call failed: {exc}")
            return None

    def run(self) -> bool:
        print("\n" + "="*65)
        print("  PHASE 1 — ACR Build & Push")
        print("="*65)
        print(f"  Registry   : {self.acr_name}")
        print(f"  Image      : {self.full_image_ref}")
        print(f"  Build ctx  : {REPO_ROOT}")

        cmd = self._build_cmd()
        for attempt in range(1, self.max_retries + 1):
            print(f"\n{'─'*65}")
            print(f"  ACR Build Attempt {attempt}/{self.max_retries}")
            print(f"{'─'*65}")
            rc, stdout, stderr = run_cmd(cmd, dry_run=self.dry_run)

            if rc == 0:
                print(f"\n✅ ACR build & push SUCCEEDED! Image: {self.full_image_ref}")
                return True

            print(f"\n❌ ACR build FAILED (exit code {rc}).")
            error_text = f"STDOUT:\n{stdout[-2000:]}\n\nSTDERR:\n{stderr[-2000:]}"
            print("\n[K8s/ACR Agent] Consulting Gemini for ACR fix…")
            fix = self._ask_gemini_fix(error_text)

            if fix:
                print(f"  Diagnosis: {fix.get('diagnosis', '')[:300]}")
                for corr in fix.get("corrections", []):
                    rel = corr.get("file_path", "")
                    content = corr.get("corrected_content", "")
                    if not rel or not content:
                        continue
                    full = REPO_ROOT / rel
                    print(f"  Applying fix → {rel}")
                    if not self.dry_run:
                        full.parent.mkdir(parents=True, exist_ok=True)
                        full.write_text(content, encoding='utf-8')
                override = fix.get("az_command_override", [])
                if override:
                    cmd = override
                    print(f"  Using corrected az command: {' '.join(cmd)}")

        print(f"\n⛔ ACR build failed after {self.max_retries} attempts.")
        return False


