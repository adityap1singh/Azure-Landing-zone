"""
Kubernetes + ACR Agent — Build, Push & Deploy with Error-Rectify-Rerun Loop
============================================================================
Responsibilities:
  1. ACR BUILD & PUSH  — Run `az acr build` to build the Docker image from the
                         repo-root Dockerfile and push it to Azure Container Registry.
  2. AKS CREDENTIALS   — Run `az aks get-credentials` to configure kubectl.
  3. K8S DEPLOY        — Apply Kubernetes manifests (from k8s/ directory, or
                         auto-generated by Gemini if none exist).
  4. HEALTH CHECK      — Wait for Deployments to reach Ready state.
  5. ERROR-RECTIFY-RERUN — On any `az` or `kubectl` error, send the error +
                         current manifests to Gemini for a corrected version,
                         write the fix, and retry — up to MAX_RETRIES times.

Usage:
  python k8s_acr_agent.py [--dry-run] [--skip-build] [--skip-deploy] [--max-retries N]

Environment variables (ai_agents/.env):
  GEMINI_API_KEY         — Google Gemini API key
  AZURE_SUBSCRIPTION_ID  — Target Azure subscription
  AZURE_TENANT_ID        — Azure tenant ID
  AZURE_CLIENT_ID        — Service Principal client ID
  AZURE_CLIENT_SECRET    — Service Principal client secret
  ACR_NAME               — ACR registry name (e.g. myacr)
  ACR_LOGIN_SERVER       — ACR login server (e.g. myacr.azurecr.io)
  AKS_CLUSTER_NAME       — AKS cluster name
  RESOURCE_GROUP         — Azure resource group containing AKS + ACR
  IMAGE_NAME             — Docker image name (e.g. myapp)
  IMAGE_TAG              — Docker image tag (default: latest)
  K8S_NAMESPACE          — Target Kubernetes namespace (default: default)
  K8S_MAX_RETRIES        — Max error-rectify cycles (default: 3)
"""

