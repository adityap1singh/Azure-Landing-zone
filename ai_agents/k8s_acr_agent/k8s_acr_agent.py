def run_cmd(
    args: list[str],
    dry_run: bool = False,
    capture: bool = True,
    env_extra: dict = None,
) -> tuple[int, str, str]:
    """
    Run a shell command and return (returncode, stdout, stderr).
    Merges env_extra into the current environment if provided.
    """
    print(f"  [cmd] {' '.join(args)}")
    if dry_run:
        print("    [DRY RUN] Skipping.")
        return 0, "[DRY RUN]", ""

    env = os.environ.copy()
    if env_extra:
        env.update(env_extra)

    result = subprocess.run(args, capture_output=capture, text=True, env=env)
    if result.stdout:
        print(result.stdout[-3000:])
    if result.stderr:
        print(result.stderr[-2000:])
    return result.returncode, result.stdout, result.stderr


def az_login(dry_run: bool) -> bool:
    """Login to Azure using Service Principal credentials from env."""
    client_id = get_env("AZURE_CLIENT_ID")
    client_secret = get_env("AZURE_CLIENT_SECRET")
    tenant_id = get_env("AZURE_TENANT_ID")

    if not all([client_id, client_secret, tenant_id]):
        print("  [INFO] Azure SP credentials not set — assuming already logged in via az cli.")
        return True

    print("\n[K8s/ACR Agent] Logging in to Azure…")
    rc, _, _ = run_cmd(
        ["az", "login", "--service-principal",
         "--username", client_id,
         "--password", client_secret,
         "--tenant", tenant_id],
        dry_run=dry_run,
    )
    if rc != 0:
        print("  [ERROR] Azure login failed.")
        return False

    sub_id = get_env("AZURE_SUBSCRIPTION_ID")
    if sub_id:
        run_cmd(["az", "account", "set", "--subscription", sub_id], dry_run=dry_run)

    print("  ✓ Azure login successful.")
    return True


