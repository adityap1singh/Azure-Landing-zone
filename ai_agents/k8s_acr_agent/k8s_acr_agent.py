class K8sDeployPhase:
    def __init__(
        self,
        manifest_files: list[Path],
        namespace: str,
        image_name: str,
        full_image_ref: str,
        dry_run: bool,
        client: genai.Client,
        max_retries: int,
    ):
        self.manifest_files = manifest_files
        self.namespace = namespace
        self.image_name = image_name
        self.full_image_ref = full_image_ref
        self.dry_run = dry_run
        self.client = client
        self.max_retries = max_retries

    def _apply_manifests(self) -> tuple[int, str, str]:
        """Run kubectl apply for all manifest files."""
        for mf in self.manifest_files:
            rc, stdout, stderr = run_cmd(
                ["kubectl", "apply", "-f", str(mf), "-n", self.namespace],
                dry_run=self.dry_run,
            )
            if rc != 0:
                return rc, stdout, stderr
        return 0, "All manifests applied.", ""

    def _wait_for_ready(self) -> bool:
        """Poll until Deployment rollout is complete or timeout."""
        print(f"\n  Waiting for Deployment '{self.image_name}' to become Ready…")
        elapsed = 0
        while elapsed < HEALTH_TIMEOUT:
            rc, stdout, _ = run_cmd(
                ["kubectl", "rollout", "status",
                 f"deployment/{self.image_name}",
                 "-n", self.namespace,
                 "--timeout=30s"],
                dry_run=self.dry_run,
            )
            if rc == 0:
                print("  ✓ Deployment is Ready!")
                return True
            time.sleep(HEALTH_POLL_INTERVAL)
            elapsed += HEALTH_POLL_INTERVAL
            print(f"  [{elapsed}s] Still waiting…")
        print("  [WARN] Timed out waiting for Deployment to become Ready.")
        return False

    def _get_pod_events(self) -> str:
        """Collect recent events and pod status for debugging."""
        _, events, _ = run_cmd(
            ["kubectl", "get", "events", "-n", self.namespace,
             "--sort-by=.metadata.creationTimestamp", "--field-selector",
             f"involvedObject.name={self.image_name}"],
            dry_run=self.dry_run,
        )
        _, pods, _ = run_cmd(
            ["kubectl", "get", "pods", "-n", self.namespace,
             "-l", f"app={self.image_name}", "-o", "wide"],
            dry_run=self.dry_run,
        )
        _, describe, _ = run_cmd(
            ["kubectl", "describe", "deployment", self.image_name,
             "-n", self.namespace],
            dry_run=self.dry_run,
        )
        return f"EVENTS:\n{events}\n\nPODS:\n{pods}\n\nDESCRIBE:\n{describe}"

    def _ask_gemini_fix(self, error_output: str) -> dict | None:
        """Send error context to Gemini for manifest corrections."""
        manifest_content = ""
        for mf in self.manifest_files:
            try:
                manifest_content += f"\n--- {mf.name} ---\n{mf.read_text(encoding='utf-8')}\n"
            except Exception:
                pass

        prompt = f"""You are a Kubernetes and Azure AKS expert.
A Kubernetes deployment failed. Diagnose the issue and provide corrected manifest files.

## ERROR OUTPUT
{error_output}

## CURRENT MANIFESTS
{manifest_content}

## DEPLOYMENT CONTEXT
- Image: {self.full_image_ref}
- Namespace: {self.namespace}
- Application: {self.image_name}

Respond ONLY with a JSON block inside ```json ... ```:
```json
{{
  "diagnosis": "Root cause explanation",
  "corrections": [
    {{
      "file_path": "k8s/filename.yaml",
      "corrected_content": "Full corrected YAML content"
    }}
  ]
}}
```
- file_path is relative to the repository root.
- corrected_content is the COMPLETE file content.
- If the issue is transient (e.g. image pull backoff that just needs time), set corrections to [].
"""
        try:
            from llm_client import generate_text_with_retry
            raw = generate_text_with_retry(self.client, prompt)
            if "```json" in raw:
                json_str = raw.split("```json")[1].split("```")[0].strip()
            elif "```" in raw:
                json_str = raw.split("```")[1].split("```")[0].strip()
            else:
                json_str = raw
            return json.loads(json_str)
        except Exception as exc:
            print(f"  [ERROR] Gemini call failed: {exc}")
            return None

    def run(self) -> bool:
        print("\n" + "="*65)
        print("  PHASE 4 — Kubernetes Deploy")
        print("="*65)
        print(f"  Namespace  : {self.namespace}")
        print(f"  Manifests  : {[str(m.name) for m in self.manifest_files]}")

        # Ensure namespace exists
        run_cmd(
            ["kubectl", "create", "namespace", self.namespace,
             "--dry-run=client", "-o", "yaml"],
            dry_run=self.dry_run,
        )
        run_cmd(
            ["kubectl", "apply", "-f", "-"],
            dry_run=self.dry_run,
        )

        # Create namespace idempotently
        run_cmd(
            ["kubectl", "get", "namespace", self.namespace],
            dry_run=self.dry_run,
        )

        for attempt in range(1, self.max_retries + 1):
            print(f"\n{'─'*65}")
            print(f"  K8s Deploy Attempt {attempt}/{self.max_retries}")
            print(f"{'─'*65}")

            # Apply manifests
            rc, stdout, stderr = self._apply_manifests()
            if rc != 0:
                error_text = f"kubectl apply FAILED\nSTDOUT:\n{stdout}\nSTDERR:\n{stderr}"
                print(f"\n❌ {error_text[:500]}")
                fix = self._ask_gemini_fix(error_text)
                if fix:
                    self._apply_corrections(fix.get("corrections", []))
                continue

            # Wait for rollout
            ready = self._wait_for_ready()
            if ready:
                print("\n✅ Kubernetes deployment COMPLETE!")
                self._print_endpoint()
                return True

            # Rollout not ready — collect events and ask Gemini
            print("\n❌ Deployment did not become Ready in time.")
            events = self._get_pod_events()
            fix = self._ask_gemini_fix(events)
            if fix:
                print(f"  Diagnosis: {fix.get('diagnosis', '')[:300]}")
                self._apply_corrections(fix.get("corrections", []))

        print(f"\n⛔ K8s deploy failed after {self.max_retries} attempts.")
        return False

    def _apply_corrections(self, corrections: list[dict]):
        for corr in corrections:
            rel = corr.get("file_path", "").strip()
            content = corr.get("corrected_content", "")
            if not rel or not content:
                continue
            full = REPO_ROOT / rel
            print(f"  Applying manifest fix → {rel}")
            if not self.dry_run:
                full.parent.mkdir(parents=True, exist_ok=True)
                full.write_text(content, encoding='utf-8')
            # Refresh manifest file list if the file was updated
            for i, mf in enumerate(self.manifest_files):
                if mf.name == full.name:
                    self.manifest_files[i] = full

    def _print_endpoint(self):
        """Print the external IP / hostname of the LoadBalancer service."""
        print("\n  Fetching service endpoint…")
        for _ in range(10):
            rc, stdout, _ = run_cmd(
                ["kubectl", "get", "svc", f"{self.image_name}-service",
                 "-n", self.namespace,
                 "-o", "jsonpath={.status.loadBalancer.ingress[0].ip}"],
                dry_run=self.dry_run,
            )
            ip = stdout.strip()
            if ip and ip != "[DRY RUN]":
                print(f"\n  🌐 Application endpoint: http://{ip}")
                return
            time.sleep(10)
        print("  [INFO] External IP not yet assigned — check `kubectl get svc` later.")


class K8sAcrAgent:
    """
    Programmatic interface for the Orchestrator and external tools.
    """

    def __init__(self, dry_run: bool = False):
        self.dry_run = dry_run
        self.client = get_gemini_client()

    def run(self, args: dict = None) -> bool:
        args = args or {}
        dry_run = args.get("dry_run", self.dry_run)
        max_retries = int(args.get("max_retries", DEFAULT_MAX_RETRIES))
        skip_build = args.get("skip_build", False)
        skip_deploy = args.get("skip_deploy", False)

        namespace = args.get("namespace") or get_env("K8S_NAMESPACE", "default")
        image_name = args.get("image_name") or get_env("IMAGE_NAME", "app")
        image_tag = args.get("image_tag") or get_env("IMAGE_TAG", "latest")
        acr_name = args.get("acr_name") or get_env("ACR_NAME", required=True)
        acr_login_server = args.get("acr_login_server") or get_env("ACR_LOGIN_SERVER") or f"{acr_name}.azurecr.io"
        full_image_ref = f"{acr_login_server}/{image_name}:{image_tag}"
        
        build_context_dir = Path(args["build_context_dir"]) if args.get("build_context_dir") else (
            Path(args["app_dir"]) if args.get("app_dir") else REPO_ROOT
        )

        print("=" * 65)
        print("  K8s + ACR Agent — Build, Push & Deploy")
        print(f"  ACR Name  : {acr_name}")
        print(f"  Image     : {full_image_ref}")
        print(f"  Build Dir : {build_context_dir}")
        print(f"  AKS       : {get_env('AKS_CLUSTER_NAME', 'N/A')}")
        print(f"  Namespace : {namespace}")
        print(f"  Dry Run   : {dry_run}")
        print(f"  MaxRetries: {max_retries}")
        print("=" * 65)

        # Azure login
        if not az_login(dry_run):
            return False

        # Phase 1 — ACR Build & Push
        if not skip_build:
            acr_phase = AcrPhase(
                dry_run=dry_run,
                client=self.client,
                max_retries=max_retries,
                image_name=image_name,
                image_tag=image_tag,
                build_context_dir=build_context_dir,
                acr_name=acr_name,
            )
            success = acr_phase.run()
            if not success and not dry_run:
                print("\n[FATAL] ACR build failed. Cannot deploy without a valid image.")
                return False

        if skip_deploy:
            print("\n[INFO] --skip-deploy flag set. Skipping Kubernetes deployment.")
            print("[K8s/ACR Agent] Done.")
            return True

        # Phase 2 — AKS Credentials
        if not get_aks_credentials(dry_run):
            return False

        # Phase 3 — Manifests
        manifest_files = ensure_manifests(
            image_name=image_name,
            full_image_ref=full_image_ref,
            namespace=namespace,
            client=self.client,
            dry_run=dry_run,
        )

        # Phase 4 — Deploy + Error-Rectify-Rerun
        k8s_phase = K8sDeployPhase(
            manifest_files=manifest_files,
            namespace=namespace,
            image_name=image_name,
            full_image_ref=full_image_ref,
            dry_run=dry_run,
            client=self.client,
            max_retries=max_retries,
        )
        success = k8s_phase.run()
        print("\n[K8s/ACR Agent] Done.")
        return success


